using System.Windows;
using System.Windows.Controls;
using Binding = System.Windows.Data.Binding;

namespace DM_RMS.Wpf.Behaviors;

/// <summary>
/// 쉼표, 세미콜론 또는 파이프로 전달한 컬럼 이름 목록을 DataGrid에서 숨깁니다.
/// 자동 생성 컬럼과 XAML에 명시한 컬럼을 모두 지원하며, 명시 컬럼은 Binding 경로를 우선 비교합니다.
/// </summary>
public static class DataGridHiddenColumnsBehavior
{
    public static readonly DependencyProperty HiddenColumnsProperty = DependencyProperty.RegisterAttached(
        "HiddenColumns", typeof(string), typeof(DataGridHiddenColumnsBehavior),
        new PropertyMetadata(string.Empty, OnHiddenColumnsChanged));

    public static string GetHiddenColumns(DependencyObject obj) => (string)obj.GetValue(HiddenColumnsProperty);
    public static void SetHiddenColumns(DependencyObject obj, string value) => obj.SetValue(HiddenColumnsProperty, value);

    private static void OnHiddenColumnsChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not DataGrid grid) return;

        grid.AutoGeneratingColumn -= OnAutoGeneratingColumn;
        grid.AutoGeneratingColumn += OnAutoGeneratingColumn;
        grid.AutoGeneratedColumns -= OnAutoGeneratedColumns;
        grid.AutoGeneratedColumns += OnAutoGeneratedColumns;
        grid.Loaded -= OnLoaded;
        grid.Loaded += OnLoaded;
        Apply(grid);
    }

    private static void OnLoaded(object sender, RoutedEventArgs e)
    {
        if (sender is DataGrid grid) Apply(grid);
    }

    private static void OnAutoGeneratedColumns(object? sender, EventArgs e)
    {
        if (sender is DataGrid grid) Apply(grid);
    }

    private static void OnAutoGeneratingColumn(object? sender, DataGridAutoGeneratingColumnEventArgs e)
    {
        if (sender is not DataGrid grid) return;
        if (GetNames(grid).Contains(e.PropertyName)) e.Cancel = true;
    }

    private static void Apply(DataGrid grid)
    {
        var names = GetNames(grid);
        foreach (var column in grid.Columns)
        {
            var key = GetColumnKey(column);
            column.Visibility = names.Contains(key) ? Visibility.Collapsed : Visibility.Visible;
        }
    }

    /// <summary>
    /// 컬럼을 식별할 때 Binding 경로, SortMemberPath, Header 순서로 확인합니다.
    /// 예를 들어 Header가 "Type"이어도 Binding이 ControlType이면 "ControlType"으로 숨길 수 있습니다.
    /// </summary>
    private static string GetColumnKey(DataGridColumn column)
    {
        if (column is DataGridBoundColumn boundColumn && boundColumn.Binding is Binding binding)
        {
            var bindingPath = binding.Path?.Path;
            if (!string.IsNullOrWhiteSpace(bindingPath)) return bindingPath;
        }

        if (!string.IsNullOrWhiteSpace(column.SortMemberPath)) return column.SortMemberPath;
        return column.Header?.ToString() ?? string.Empty;
    }

    private static HashSet<string> GetNames(DataGrid grid) =>
        GetHiddenColumns(grid)
            .Split(new[] { ',', ';', '|' }, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
}
