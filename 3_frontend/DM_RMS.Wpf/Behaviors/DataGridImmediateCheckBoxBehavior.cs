using System.Data;

namespace DM_RMS.Wpf.Behaviors;

/// <summary>
/// DataGridCheckBoxColumn의 기본 커밋 타이밍(포커스 이동 후 반영)을 우회하여
/// 지정 컬럼을 클릭하는 즉시 DataRowView 값을 토글한다.
/// DataTable/DataView 기반 화면에서 선택 목록을 즉시 동기화할 때 사용한다.
/// </summary>
public static class DataGridImmediateCheckBoxBehavior
{
    public static readonly System.Windows.DependencyProperty SelectionColumnNameProperty =
        System.Windows.DependencyProperty.RegisterAttached(
            "SelectionColumnName",
            typeof(string),
            typeof(DataGridImmediateCheckBoxBehavior),
            new System.Windows.PropertyMetadata(null, OnSelectionColumnNameChanged));

    public static readonly System.Windows.DependencyProperty EnableSelectAllHeaderProperty =
        System.Windows.DependencyProperty.RegisterAttached(
            "EnableSelectAllHeader",
            typeof(bool),
            typeof(DataGridImmediateCheckBoxBehavior),
            new System.Windows.PropertyMetadata(false, OnSelectAllHeaderOptionChanged));

    public static readonly System.Windows.DependencyProperty SelectAllCommandProperty =
        System.Windows.DependencyProperty.RegisterAttached(
            "SelectAllCommand",
            typeof(System.Windows.Input.ICommand),
            typeof(DataGridImmediateCheckBoxBehavior),
            new System.Windows.PropertyMetadata(null, OnSelectAllHeaderOptionChanged));

    public static readonly System.Windows.DependencyProperty SelectAllStateProperty =
        System.Windows.DependencyProperty.RegisterAttached(
            "SelectAllState",
            typeof(bool?),
            typeof(DataGridImmediateCheckBoxBehavior),
            new System.Windows.PropertyMetadata(false));

    public static string? GetSelectionColumnName(System.Windows.DependencyObject obj)
        => (string?)obj.GetValue(SelectionColumnNameProperty);

    public static void SetSelectionColumnName(System.Windows.DependencyObject obj, string? value)
        => obj.SetValue(SelectionColumnNameProperty, value);

    public static bool GetEnableSelectAllHeader(System.Windows.DependencyObject obj)
        => (bool)obj.GetValue(EnableSelectAllHeaderProperty);

    public static void SetEnableSelectAllHeader(System.Windows.DependencyObject obj, bool value)
        => obj.SetValue(EnableSelectAllHeaderProperty, value);

    public static System.Windows.Input.ICommand? GetSelectAllCommand(System.Windows.DependencyObject obj)
        => (System.Windows.Input.ICommand?)obj.GetValue(SelectAllCommandProperty);

    public static void SetSelectAllCommand(System.Windows.DependencyObject obj, System.Windows.Input.ICommand? value)
        => obj.SetValue(SelectAllCommandProperty, value);

    public static bool? GetSelectAllState(System.Windows.DependencyObject obj)
        => (bool?)obj.GetValue(SelectAllStateProperty);

    public static void SetSelectAllState(System.Windows.DependencyObject obj, bool? value)
        => obj.SetValue(SelectAllStateProperty, value);

    private static void OnSelectionColumnNameChanged(System.Windows.DependencyObject d, System.Windows.DependencyPropertyChangedEventArgs e)
    {
        if (d is not System.Windows.Controls.DataGrid dataGrid) return;

        dataGrid.PreviewMouseLeftButtonDown -= OnPreviewMouseLeftButtonDown;
        dataGrid.CurrentCellChanged -= OnCurrentCellChanged;
        dataGrid.AutoGeneratedColumns -= OnAutoGeneratedColumns;

        if (!string.IsNullOrWhiteSpace(e.NewValue as string))
        {
            dataGrid.PreviewMouseLeftButtonDown += OnPreviewMouseLeftButtonDown;
            dataGrid.CurrentCellChanged += OnCurrentCellChanged;
            dataGrid.AutoGeneratedColumns += OnAutoGeneratedColumns;
            ApplySelectAllHeader(dataGrid);
        }
    }

    private static void OnSelectAllHeaderOptionChanged(System.Windows.DependencyObject d, System.Windows.DependencyPropertyChangedEventArgs e)
    {
        if (d is System.Windows.Controls.DataGrid dataGrid)
            ApplySelectAllHeader(dataGrid);
    }

    private static void OnAutoGeneratedColumns(object? sender, EventArgs e)
    {
        if (sender is System.Windows.Controls.DataGrid dataGrid)
            ApplySelectAllHeader(dataGrid);
    }

    private static void ApplySelectAllHeader(System.Windows.Controls.DataGrid dataGrid)
    {
        if (!GetEnableSelectAllHeader(dataGrid)) return;

        var columnName = GetSelectionColumnName(dataGrid);
        if (string.IsNullOrWhiteSpace(columnName)) return;

        var targetColumn = dataGrid.Columns.FirstOrDefault(column => IsTargetColumn(column, columnName));
        if (targetColumn == null) return;

        var checkBox = new System.Windows.Controls.CheckBox
        {
            IsThreeState = true,
            HorizontalAlignment = System.Windows.HorizontalAlignment.Center,
            VerticalAlignment = System.Windows.VerticalAlignment.Center,
            ToolTip = "현재 필터 결과 전체 선택/해제"
        };

        checkBox.SetBinding(
            System.Windows.Controls.Primitives.ToggleButton.IsCheckedProperty,
            new System.Windows.Data.Binding
            {
                Source = dataGrid,
                Path = new System.Windows.PropertyPath("(0)", SelectAllStateProperty),
                Mode = System.Windows.Data.BindingMode.OneWay
            });

        checkBox.Click += (_, _) =>
        {
            var command = GetSelectAllCommand(dataGrid);
            var desiredState = checkBox.IsChecked == true;
            if (command?.CanExecute(desiredState) == true)
                command.Execute(desiredState);
        };

        targetColumn.Header = checkBox;
    }

    private static void OnCurrentCellChanged(object? sender, EventArgs e)
    {
        // 키보드 조작 또는 예외 케이스에서도 편집 값이 남지 않도록 방어적으로 커밋한다.
        if (sender is System.Windows.Controls.DataGrid dataGrid)
        {
            dataGrid.CommitEdit(System.Windows.Controls.DataGridEditingUnit.Cell, true);
            dataGrid.CommitEdit(System.Windows.Controls.DataGridEditingUnit.Row, true);
        }
    }

    private static void OnPreviewMouseLeftButtonDown(object sender, System.Windows.Input.MouseButtonEventArgs e)
    {
        if (sender is not System.Windows.Controls.DataGrid dataGrid) return;

        var columnName = GetSelectionColumnName(dataGrid);
        if (string.IsNullOrWhiteSpace(columnName)) return;

        var source = e.OriginalSource as System.Windows.DependencyObject;
        var cell = FindAncestor<System.Windows.Controls.DataGridCell>(source);
        var row = FindAncestor<System.Windows.Controls.DataGridRow>(source);

        if (cell == null || row == null) return;
        if (!IsTargetColumn(cell.Column, columnName)) return;
        if (row.Item is not DataRowView rowView) return;
        if (!rowView.Row.Table.Columns.Contains(columnName)) return;

        var current = ToBool(rowView[columnName]);
        rowView[columnName] = !current;

        dataGrid.CommitEdit(System.Windows.Controls.DataGridEditingUnit.Cell, true);
        dataGrid.CommitEdit(System.Windows.Controls.DataGridEditingUnit.Row, true);

        // 기본 CheckBox/DataGrid 편집 동작이 다시 한 번 토글하지 않도록 차단한다.
        e.Handled = true;
    }

    private static bool IsTargetColumn(System.Windows.Controls.DataGridColumn column, string columnName)
    {
        if (column is System.Windows.Controls.DataGridBoundColumn boundColumn && boundColumn.Binding is System.Windows.Data.Binding binding)
        {
            return string.Equals(binding.Path?.Path, columnName, StringComparison.OrdinalIgnoreCase);
        }

        return string.Equals(Convert.ToString(column.Header), columnName, StringComparison.OrdinalIgnoreCase)
               || string.Equals(Convert.ToString(column.SortMemberPath), columnName, StringComparison.OrdinalIgnoreCase);
    }

    private static bool ToBool(object? value)
    {
        if (value is bool b) return b;
        return bool.TryParse(Convert.ToString(value), out var parsed) && parsed;
    }

    private static T? FindAncestor<T>(System.Windows.DependencyObject? current) where T : System.Windows.DependencyObject
    {
        while (current != null)
        {
            if (current is T target) return target;
            current = current is System.Windows.Controls.Primitives.Popup popup ? popup.PlacementTarget : System.Windows.Media.VisualTreeHelper.GetParent(current);
        }

        return null;
    }
}
