    private static readonly DependencyProperty CollectionChangedHandlerProperty =
    DependencyProperty.RegisterAttached(
        "CollectionChangedHandler",
        typeof(NotifyCollectionChangedEventHandler),
        typeof(DataGridColumnFilterHeaderBehavior),
        new PropertyMetadata(null));

    private static void OnFiltersSourceChanged(
        DependencyObject dependencyObject,
        DependencyPropertyChangedEventArgs args)
    {
        if (dependencyObject is not DataGrid dataGrid)
        {
            return;
        }

        dataGrid.AutoGeneratedColumns -= OnAutoGeneratedColumns;
        dataGrid.Loaded -= OnDataGridLoaded;

        if (args.OldValue is INotifyCollectionChanged oldCollection)
        {
            var oldHandler =
                (NotifyCollectionChangedEventHandler?)
                dataGrid.GetValue(CollectionChangedHandlerProperty);

            if (oldHandler is not null)
            {
                oldCollection.CollectionChanged -= oldHandler;
            }
        }

        dataGrid.AutoGeneratedColumns += OnAutoGeneratedColumns;
        dataGrid.Loaded += OnDataGridLoaded;

        if (args.NewValue is INotifyCollectionChanged newCollection)
        {
            NotifyCollectionChangedEventHandler handler =
                (_, _) =>
                {
                    // 컬럼 생성 및 Layout 처리 후 실행되도록 Dispatcher에 예약합니다.
                    dataGrid.Dispatcher.BeginInvoke(
                        new Action(
                            () => ApplyFilterHeaders(dataGrid)),
                        System.Windows.Threading.DispatcherPriority.Loaded);
                };

            dataGrid.SetValue(
                CollectionChangedHandlerProperty,
                handler);

            newCollection.CollectionChanged += handler;
        }

        dataGrid.Dispatcher.BeginInvoke(
            new Action(
                () => ApplyFilterHeaders(dataGrid)),
            System.Windows.Threading.DispatcherPriority.Loaded);
    }

    private static void OnAutoGeneratedColumns(object? sender, EventArgs e)
    {
        if (sender is not DataGrid dataGrid)
        {
            return;
        }

        dataGrid.Dispatcher.BeginInvoke(
            new Action(
                () => ApplyFilterHeaders(dataGrid)),
            System.Windows.Threading.DispatcherPriority.Loaded);
    }

    private static void ApplyFilterHeaders(DataGrid dataGrid)
    {
        ResetFilterHeaders(dataGrid);

        var filters = GetFiltersSource(dataGrid)?.Cast<object>()
            .OfType<RecipeColumnFilter>()
            .ToDictionary(x => x.ColumnName, StringComparer.OrdinalIgnoreCase);

        if (filters == null || filters.Count == 0) return;

        foreach (var column in dataGrid.Columns)
        {
            //if (column.Header is StackPanel existingPanel &&
            //    string.Equals(existingPanel.Tag as string, "DMRMS_FILTER_HEADER", StringComparison.Ordinal))
            //{
            //    continue;
            //}

            var columnName = GetColumnName(column);
            if (string.IsNullOrWhiteSpace(columnName)
                || string.Equals(columnName, "is_selected", StringComparison.OrdinalIgnoreCase)
                || !filters.TryGetValue(columnName, out var filter))
            {
                continue;
            }

            var displayName = column.Header is string headerText && !string.IsNullOrWhiteSpace(headerText)
                ? headerText
                : filter.DisplayName;

            //Brush? headerBackground = GetHeaderBackground(column.Header);
            Brush? headerBackground =
                column.GetValue(
                    OriginalHeaderBackgroundProperty) as Brush
                    ?? GetHeaderBackground(column.Header);
            if (headerBackground is not null)
            {
                column.SetValue(OriginalHeaderBackgroundProperty, headerBackground);
            }

            var panel = new StackPanel
            {
                Tag = "DMRMS_FILTER_HEADER",
                Orientation = Orientation.Vertical,
                MinWidth = 92,
                HorizontalAlignment = System.Windows.HorizontalAlignment.Stretch
            };

            //if (column.Header is System.Windows.FrameworkElement visualHeader)
            //{
            //    column.Header = null;
            //    visualHeader.Margin = new System.Windows.Thickness(0, 0, 0, 4);
            //    panel.Children.Add(visualHeader);
            //}
            //panel.Children.Add(
            //    new TextBlock
            //    {
            //        Text = displayName,
            //        FontWeight = FontWeights.SemiBold,
            //        Margin = new Thickness(1, 0, 1, 4),
            //        TextTrimming = TextTrimming.CharacterEllipsis
            //    }
            //);
            var headerBorder = new Border
            {
                Background = headerBackground ?? Brushes.Transparent,
                Padding = new Thickness(4, 3, 4, 3),
                Margin = new Thickness(0, 0, 0, 4),
                HorizontalAlignment = System.Windows.HorizontalAlignment.Stretch,
                Child = new TextBlock
                {
                    Text = displayName,
                    FontWeight = FontWeights.SemiBold,
                    TextTrimming = TextTrimming.CharacterEllipsis,
                    HorizontalAlignment = System.Windows.HorizontalAlignment.Center,
                    TextAlignment = TextAlignment.Center,
                }
            };
            panel.Children.Add(headerBorder);
            //else
            //{
            //    panel.Children.Add(new TextBlock
            //    {
            //        Text = displayName,
            //        FontWeight = System.Windows.FontWeights.SemiBold,
            //        Margin = new System.Windows.Thickness(1, 0, 1, 4),
            //        TextTrimming = System.Windows.TextTrimming.CharacterEllipsis
            //    });
            //}

            System.Windows.FrameworkElement filterControl;
            if (filter.IsComboBox)
            {
                var comboBox = new ComboBox
                {
                    MinWidth = 92,
                    Height = 25,
                    ItemsSource = filter.Options,
                    HorizontalContentAlignment = System.Windows.HorizontalAlignment.Stretch
                };
                comboBox.SetBinding(
                    ComboBox.SelectedItemProperty,
                    new Binding(nameof(RecipeColumnFilter.SelectedValue))
                    {
                        Source = filter,
                        Mode = BindingMode.TwoWay,
                        UpdateSourceTrigger = UpdateSourceTrigger.PropertyChanged
                    });
                filterControl = comboBox;
            }
            else
            {
                var textBox = new TextBox
                {
                    MinWidth = 92,
                    Height = 25,
                    Padding = new System.Windows.Thickness(5, 1, 5, 1),
                    VerticalContentAlignment = System.Windows.VerticalAlignment.Center
                };
                textBox.SetBinding(
                    TextBox.TextProperty,
                    new Binding(nameof(RecipeColumnFilter.TextValue))
                    {
                        Source = filter,
                        Mode = BindingMode.TwoWay,
                        UpdateSourceTrigger = UpdateSourceTrigger.PropertyChanged
                    });
                filterControl = textBox;
            }

            panel.Children.Add(filterControl);
            column.Header = panel;
        }
    }

    private static Brush? GetHeaderBackground(object header)
    {
        if (header is Border border && border.Background is not null)
        {
            return border.Background;
        }
        if (header is ContentControl contentControl && contentControl.Background is not null)
        {
            return contentControl.Background;
        }
        if (header is Panel panel && panel.Background is not null)
        {
            return panel.Background;
        }
        if (header is StackPanel stackPanel)
        {
            foreach (UIElement child in stackPanel.Children)
            {
                if (child is Border childBorder && childBorder.Background is not null)
                {
                    return childBorder.Background;
                }
                if (child is Control childControl && childControl.Background is not null)
                {
                    return childControl.Background;
                }
            }
        }
        return null;
    }

    private static void ResetFilterHeaders(DataGrid dataGrid)
    {
        foreach (DataGridColumn column in dataGrid.Columns)
        {
            if (column.Header is StackPanel panel &&
                string.Equals(
                    panel.Tag as string,
                    "DMRMS_FILTER_HEADER",
                    StringComparison.Ordinal))
            {
                //TextBlock? textBlock = panel.Children.OfType<TextBlock>().FirstOrDefault();
                string? headerText = null;

                foreach (UIElement child in panel.Children)
                {
                    if (child is TextBlock textBlock)
                    {
                        headerText = textBlock.Text;
                        break;
                    }
                    if (child is Border border && border.Child is TextBlock borderTextBlock)
                    {
                        headerText = borderTextBlock.Text;
                        break;
                    }
                }
                //column.Header = textBlock?.Text ?? GetColumnName(column) ?? string.Empty;
                column.Header = headerText ?? GetColumnName(column) ?? string.Empty;
            }
        }
    }

    private static string? GetColumnName(DataGridColumn column)
    {
        // 동적 시각화 컬럼은 셀 전체 행을 Binding(".")으로 전달하므로
        // 실제 원본 컬럼명인 SortMemberPath를 먼저 사용해야 한다.
        if (!string.IsNullOrWhiteSpace(column.SortMemberPath))
            return column.SortMemberPath;

        if (column is DataGridBoundColumn boundColumn && boundColumn.Binding is Binding binding)
            return binding.Path?.Path;

        return column.Header as string;
    }

    private static void OnDataGridLoaded(object sender, RoutedEventArgs args)
    {
        if (sender is not DataGrid dataGrid)
        {
            return;
        }

        dataGrid.Dispatcher.BeginInvoke(
            new Action(
                () => ApplyFilterHeaders(dataGrid)),
            System.Windows.Threading.DispatcherPriority.Loaded);
    }

    private static readonly DependencyProperty
        OriginalHeaderBackgroundProperty =
            DependencyProperty.RegisterAttached(
                "OriginalHeaderBackground",
                typeof(Brush),
                typeof(DataGridColumnFilterHeaderBehavior),
                new PropertyMetadata(null));
}
