/// <summary>
/// AutoGenerateColumns 기반 DataGrid의 각 컬럼 헤더 아래에 컬럼별 필터 컨트롤을 배치한다.
/// 텍스트 컬럼은 LIKE 성격의 TextBox, 지정된 콤보 컬럼은 ComboBox를 사용한다.
/// DataGrid의 실제 컬럼 폭/가로 스크롤과 함께 움직이므로 Excel 필터 행과 유사한 UX를 제공한다.
/// </summary>
public static class DataGridColumnFilterHeaderBehavior
{
    public static readonly System.Windows.DependencyProperty FiltersSourceProperty =
        System.Windows.DependencyProperty.RegisterAttached(
            "FiltersSource",
            typeof(IEnumerable),
            typeof(DataGridColumnFilterHeaderBehavior),
            new System.Windows.PropertyMetadata(null, OnFiltersSourceChanged));

    public static IEnumerable? GetFiltersSource(System.Windows.DependencyObject obj)
        => (IEnumerable?)obj.GetValue(FiltersSourceProperty);

    public static void SetFiltersSource(System.Windows.DependencyObject obj, IEnumerable? value)
        => obj.SetValue(FiltersSourceProperty, value);

